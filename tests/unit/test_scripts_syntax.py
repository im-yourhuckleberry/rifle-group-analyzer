import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = sorted((PROJECT_ROOT / "scripts").glob("*.sh"))
SCRIPT_IDS = [path.name for path in SCRIPTS]


def test_scripts_directory_is_not_empty() -> None:
    assert {"bootstrap.sh", "lock.sh", "run.sh", "scan.sh"} <= {p.name for p in SCRIPTS}


@pytest.mark.parametrize("script", SCRIPTS, ids=SCRIPT_IDS)
def test_bash_syntax(script: Path) -> None:
    result = subprocess.run(  # noqa: S603  (fixed argv)
        ["/bin/bash", "-n", str(script)], capture_output=True, text=True, timeout=30, check=False
    )
    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize("script", SCRIPTS, ids=SCRIPT_IDS)
def test_script_hygiene(script: Path) -> None:
    text = script.read_text(encoding="utf-8")
    assert text.startswith("#!/usr/bin/env bash\n")
    assert re.search(r"^set -euo pipefail$", text, re.MULTILINE)
    assert os.access(script, os.X_OK)
    assert not re.search(r"\bread\s+-[a-z]*p", text), "interactive read is not allowed"


def test_shellcheck(capsys: pytest.CaptureFixture[str]) -> None:
    shellcheck = shutil.which("shellcheck")
    if shellcheck is None:
        with capsys.disabled():
            print("\nSHELLCHECK: NOT INSTALLED")
        pytest.skip("SHELLCHECK: NOT INSTALLED")
    result = subprocess.run(  # noqa: S603  (resolved binary, fixed argv)
        [shellcheck, *map(str, SCRIPTS)], capture_output=True, text=True, timeout=120, check=False
    )
    assert result.returncode == 0, result.stdout



@dataclass
class PipAuditStub:
    """Replays `output` (written to --output) and exits `exit_code`; `real` runs the real tool."""

    output: dict | None = field(default_factory=lambda: PIP_AUDIT_CLEAN)
    exit_code: int = 0
    real: bool = False


@dataclass
class BanditStub:
    """Default wraps the real bandit; the fields force a different outcome."""

    run_real: bool = True
    exit_code: int | None = None
    output: dict | None = None


@dataclass
class ScanTree:
    root: Path
    pip_audit_argv: Path

    @property
    def results(self) -> Path:
        return self.root / ".claude" / "specs" / "rifle-group-analyzer"

    def pip_audit_args(self) -> list[str]:
        return self.pip_audit_argv.read_text(encoding="utf-8").splitlines()


def _tool_script(
    *,
    real: Path | None,
    output_flag: str,
    fixture: Path | None = None,
    exit_code: int | None = None,
    argv_file: Path | None = None,
) -> str:
    lines = ["#!/bin/sh"]
    if argv_file is not None:
        lines.append(f'printf "%s\\n" "$@" > "{argv_file}"')
    lines.append('out=""; prev=""')
    lines.append(f'for a in "$@"; do if [ "$prev" = "{output_flag}" ]; then out="$a"; fi; prev="$a"; done')
    if fixture is not None:
        lines.append(f'cp "{fixture}" "$out"')
    lines.append(f'"{real}" "$@"; rc=$?' if real is not None else "rc=0")
    if exit_code == KILL:
        lines.append("kill -9 $$")
    else:
        lines.append("exit $rc" if exit_code is None else f"exit {exit_code}")
    return "\n".join(lines) + "\n"


def _install(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")
    path.chmod(0o755)


def _scan_tree(
    tmp_path: Path,
    *,
    source: str | None = CLEAN_SOURCE,
    files: dict[str, str] | None = None,
    lock: str | None = DEFAULT_LOCK,
    pip_audit: PipAuditStub | None = None,
    bandit: BanditStub | None = None,
    python_exit: int | None = None,
) -> ScanTree:
    """Scratch project with the real scan.sh and pyproject.toml and a controlled `.venv/bin`."""
    pip_audit = pip_audit or PipAuditStub()
    bandit = bandit or BanditStub()
    root = tmp_path / "tree"
    bin_dir = root / ".venv" / "bin"
    bin_dir.mkdir(parents=True)
    (root / "scripts").mkdir()
    (root / "fixtures").mkdir()
    shutil.copy2(PROJECT_ROOT / "scripts" / "scan.sh", root / "scripts" / "scan.sh")
    shutil.copy2(PROJECT_ROOT / "pyproject.toml", root / "pyproject.toml")
    if lock is not None:
        (root / "requirements.lock").write_text(lock, encoding="utf-8")
    sources = {"src/mod.py": source} if source is not None else {}
    if source is not None or files:
        (root / "src").mkdir()
    for relative, content in {**sources, **(files or {})}.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    real_bin = PROJECT_ROOT / ".venv" / "bin"
    if python_exit is None:
        _install(bin_dir / "python", f'#!/bin/sh\nexec "{real_bin / "python"}" "$@"\n')
    elif python_exit == KILL:
        _install(bin_dir / "python", "#!/bin/sh\nkill -9 $$\n")
    else:
        _install(bin_dir / "python", f"#!/bin/sh\nexit {python_exit}\n")

    bandit_fixture = None
    if bandit.output is not None:
        bandit_fixture = root / "fixtures" / "bandit.json"
        bandit_fixture.write_text(json.dumps(bandit.output), encoding="utf-8")
    _install(
        bin_dir / "bandit",
        _tool_script(
            real=real_bin / "bandit" if bandit.run_real else None,
            output_flag="-o",
            fixture=bandit_fixture,
            exit_code=bandit.exit_code,
        ),
    )

    argv_file = root / "fixtures" / "pip-audit-argv.txt"
    pip_fixture = None
    if pip_audit.output is not None:
        pip_fixture = root / "fixtures" / "pip-audit.json"
        pip_fixture.write_text(json.dumps(pip_audit.output), encoding="utf-8")
    _install(
        bin_dir / "pip-audit",
        _tool_script(
            real=real_bin / "pip-audit" if pip_audit.real else None,
            output_flag="--output",
            fixture=None if pip_audit.real else pip_fixture,
            exit_code=None if pip_audit.real else pip_audit.exit_code,
            argv_file=argv_file,
        ),
    )
    return ScanTree(root=root, pip_audit_argv=argv_file)


def _scan(
    tree: ScanTree, *args: str, extra_env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    env = {"PATH": os.environ["PATH"], **(extra_env or {})}
    return subprocess.run(  # noqa: S603  (fixed argv)
        [str(tree.root / "scripts" / "scan.sh"), *args],
        env=env,
        capture_output=True,
        text=True,
        timeout=180,
        check=False,
    )


def _output(result: subprocess.CompletedProcess[str]) -> str:
    return result.stdout + result.stderr


# --- bandit gate ------------------------------------------------------------------------------


def test_scan_fails_on_a_high_severity_bandit_finding(tmp_path: Path) -> None:
    tree = _scan_tree(tmp_path, source=HIGH_SEVERITY_SOURCE)
    result = _scan(tree, "--only", "bandit")
    assert result.returncode == 1, _output(result)
    assert "high=1" in result.stdout and "B602" in result.stdout
    results = tree.results / "bandit-results.json"
    assert results.is_file() and results.stat().st_size > 0


def test_scan_passes_on_clean_source(tmp_path: Path) -> None:
    result = _scan(_scan_tree(tmp_path), "--only", "bandit")
    assert result.returncode == 0, _output(result)
    assert "high=0" in result.stdout


def test_scan_does_not_skip_source_files_whose_path_contains_an_excluded_looking_word(
    tmp_path: Path,
) -> None:
    flagged = {
        "src/rga/services/metadata_probe.py",
        "src/rga/attests/probe.py",
        "src/data/loader.py",
        "src/rga/tests/probe.py",
        "src/rga/venv_helper.py",
        "src/rga/playwright-browsers/x.py",
    }
    tree = _scan_tree(tmp_path, source=None, files=dict.fromkeys(flagged, HIGH_SEVERITY_SOURCE))
    result = _scan(tree, "--only", "bandit")
    assert result.returncode == 1, _output(result)
    assert f"high={len(flagged)}" in result.stdout
    scanned = json.loads((tree.results / "bandit-results.json").read_text(encoding="utf-8"))
    assert {item["filename"] for item in scanned["results"]} == flagged



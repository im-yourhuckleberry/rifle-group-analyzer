@pytest.mark.parametrize("lock", [None, "", HEADER_ONLY_LOCK], ids=["missing", "empty", "header-only"])
def test_missing_or_pinless_lock_is_not_run_even_if_pip_audit_reports_clean(
    lock: str | None, tmp_path: Path
) -> None:
    stub = PipAuditStub(output=PIP_AUDIT_EMPTY)
    tree = _scan_tree(tmp_path, lock=lock, pip_audit=stub)
    result = _scan(tree, "--only", "pip-audit")
    assert result.returncode == 3, _output(result)
    assert "PIP-AUDIT: NOT RUN" in result.stderr
    if not lock:
        assert not tree.pip_audit_argv.exists(), "pip-audit must not run without a lock"


def test_pip_audit_reports_not_run_without_network(tmp_path: Path) -> None:
    dead_proxy = "http://127.0.0.1:9"
    tree = _scan_tree(tmp_path, pip_audit=PipAuditStub(real=True))
    shutil.copy2(PROJECT_ROOT / "requirements.lock", tree.root / "requirements.lock")
    result = _scan(
        tree,
        "--only",
        "pip-audit",
        extra_env={"HTTPS_PROXY": dead_proxy, "HTTP_PROXY": dead_proxy, "ALL_PROXY": dead_proxy},
    )
    assert result.returncode == 3, _output(result)
    assert "PIP-AUDIT: NOT RUN" in result.stderr



# --- pip-audit gate ---------------------------------------------------------------------------


def test_pip_audit_clean_recorded_output_passes_and_uses_hashed_offline_resolution(
    tmp_path: Path,
) -> None:
    tree = _scan_tree(tmp_path)
    result = _scan(tree, "--only", "pip-audit")
    assert result.returncode == 0, _output(result)
    assert "audited 2 pinned packages; vulnerable packages=0" in result.stdout
    args = tree.pip_audit_args()
    for flag in ("--require-hashes", "--disable-pip", "--strict"):
        assert flag in args
    assert args[args.index("--requirement") + 1] == "requirements.lock"
    assert "--ignore-vuln" not in args
    assert (tree.results / "pip-audit-results.json").is_file()


def test_pip_audit_recorded_vulnerability_fails_the_scan(tmp_path: Path) -> None:
    stub = PipAuditStub(output=PIP_AUDIT_VULNERABLE, exit_code=1)
    result = _scan(_scan_tree(tmp_path, pip_audit=stub), "--only", "pip-audit")
    assert result.returncode == 1, _output(result)
    assert "vulnerable packages=1" in result.stdout
    assert "beta-pkg==2.0 PYSEC-0001 fix=2.1" in result.stdout


def test_ignore_list_is_passed_to_pip_audit_and_logged(tmp_path: Path) -> None:
    tree = _scan_tree(tmp_path)
    result = _scan(
        tree,
        "--only",
        "pip-audit",
        extra_env={"SCAN_IGNORE_VULNS": "PYSEC-0001, GHSA-aaaa-bbbb-cccc"},
    )
    assert result.returncode == 0, _output(result)
    assert "PIP-AUDIT: ignoring PYSEC-0001 (SCAN_IGNORE_VULNS)" in result.stdout
    assert "PIP-AUDIT: ignoring GHSA-aaaa-bbbb-cccc (SCAN_IGNORE_VULNS)" in result.stdout
    args = tree.pip_audit_args()
    pairs = [args[i + 1] for i, value in enumerate(args) if value == "--ignore-vuln"]
    assert pairs == ["PYSEC-0001", "GHSA-aaaa-bbbb-cccc"]


@pytest.mark.parametrize("bad", ["*", "a;b", "$(id)", "../x", "ok,--strict x"])
def test_ignore_list_rejects_malformed_ids_without_running_pip_audit(
    bad: str, tmp_path: Path
) -> None:
    tree = _scan_tree(tmp_path)
    result = _scan(tree, "--only", "pip-audit", extra_env={"SCAN_IGNORE_VULNS": bad})
    assert result.returncode == 2, _output(result)
    assert "invalid vulnerability ID" in result.stderr
    assert not tree.pip_audit_argv.exists()



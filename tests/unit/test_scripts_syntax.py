"""Script checks: syntax (`bash -n`, shellcheck when installed), hygiene, and the scan.sh gates.

scan.sh is exercised in scratch trees whose `.venv/bin` holds wrappers around the real python and
bandit and stubs that replay recorded pip-audit output, so no test needs the network.
"""

from __future__ import annotations

